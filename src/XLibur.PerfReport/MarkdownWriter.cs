using System.Globalization;
using System.Text;

namespace PerfReport;

/// <summary>Writes <c>docs/performance.md</c> and the job summary.</summary>
public static class MarkdownWriter
{
    public const string XlBenchUrl = "https://jafin.github.io/XLBench/";

    public const string XlBenchChangelogUrl = "https://github.com/jafin/XLBench/blob/main/CHANGELOG.md";

    private const string TableHeader =
        "| Release | Mean | Allocated | Allocated vs previous | Time vs median of last 5 (indicative) | Flag |\n" +
        "|---|---:|---:|---:|---:|---|\n";

    /// <summary>The page for <c>docs/performance.md</c>: the last five releases of every benchmark.</summary>
    public static string RenderHistory(IReadOnlyList<ReleaseRecord> history)
    {
        var stable = VersionOrder.Sort(history.Where(r => r.IsBaseline));
        var rowsByRecord = new Dictionary<ReleaseRecord, Dictionary<string, ComparisonRow>>();
        foreach (var record in stable)
            rowsByRecord[record] = Comparer.Compare(record, stable).ToDictionary(r => r.Entry.Key);

        var sb = new StringBuilder();
        sb.Append("# Performance history\n\n");
        sb.Append("<!-- Generated by src/XLibur.PerfReport on the perf-history branch. Do not edit by hand. -->\n\n");
        sb.Append("XLibur's own benchmarks, run on a GitHub-hosted runner when a release is published. ");
        sb.Append("A shared runner is noisy, so these numbers detect change between releases; they are not ");
        sb.Append("authoritative. Allocated bytes are deterministic and are flagged when they rise by more than ");
        sb.Append(CultureInfo.InvariantCulture, $"{Comparer.AllocThresholdPercent:0}% over the previous release. ");
        sb.Append(CultureInfo.InvariantCulture, $"Time is flagged when it is more than {Comparer.TimeThresholdPercent:0}% ");
        sb.Append("over the median of the last five releases, and is indicative only. A benchmark whose source ");
        sb.Append("or parameters changed shows `re-baselined` and is not flagged for that release. ");
        sb.Append("Pre-release tags and manual runs are stored but left out of the baselines and these tables.\n\n");
        sb.Append(CultureInfo.InvariantCulture,
            $"Comparisons with other libraries, on the published NuGet package, live in [XLBench]({XlBenchUrl}) ");
        sb.Append(CultureInfo.InvariantCulture, $"([changelog]({XlBenchChangelogUrl})).\n\n");

        if (stable.Count == 0)
        {
            sb.Append("No release has been recorded yet.\n");
            return sb.ToString();
        }

        var keys = stable.SelectMany(r => r.Benchmarks.Select(b => b.Key)).Distinct(StringComparer.Ordinal)
            .OrderBy(k => k, StringComparer.Ordinal);

        foreach (var key in keys)
        {
            var releases = stable.Where(r => r.Benchmarks.Any(b => b.Key == key)).TakeLast(Comparer.MedianWindow);
            sb.Append(CultureInfo.InvariantCulture, $"### {key}\n\n");
            sb.Append(TableHeader);
            foreach (var release in releases.Reverse())
                AppendRow(sb, release.Version, rowsByRecord[release][key]);
            sb.Append('\n');
        }

        return sb.ToString();
    }

    /// <summary>The job summary: the run just made, with its flags. Includes manual and pre-release runs.</summary>
    public static string RenderSummary(ReleaseRecord current, IReadOnlyList<ComparisonRow> rows)
    {
        var sb = new StringBuilder();
        var kind = RunKind(current);
        sb.Append(CultureInfo.InvariantCulture, $"## Benchmarks for {current.Version}{kind}\n\n");
        sb.Append(CultureInfo.InvariantCulture,
            $"Commit `{current.Commit}`, {current.RunnerImage}, {current.Cores} cores, " +
            $"peak working set {FormatBytes(current.PeakWorkingSetBytes)}.\n\n");

        if (rows.Count > 0 && rows.All(r => r.IsNew))
            sb.Append("First run for these benchmarks: history seeded, nothing to compare with, no flags.\n\n");

        sb.Append("| Benchmark | Mean | Allocated | Allocated vs previous | Time vs median of last 5 (indicative) | Flag |\n");
        sb.Append("|---|---:|---:|---:|---:|---|\n");
        foreach (var row in rows.OrderBy(r => r.Entry.Key, StringComparer.Ordinal))
            AppendRow(sb, row.Entry.Key, row);
        sb.Append('\n');
        return sb.ToString();
    }

    private static string RunKind(ReleaseRecord record)
    {
        if (record.Manual) return " (manual run: not flagged, not stored as a baseline)";
        if (record.PreRelease) return " (pre-release: compared, not used as a baseline)";
        return "";
    }

    private static void AppendRow(StringBuilder sb, string label, ComparisonRow row)
    {
        sb.Append(CultureInfo.InvariantCulture,
            $"| {label} | {FormatTime(row.Entry.MeanNs)} | {FormatBytes(row.Entry.AllocatedBytes)} | " +
            $"{FormatDelta(row.AllocDeltaPercent)} | {FormatDelta(row.TimeDeltaPercent)} | {FlagText(row)} |\n");
    }

    private static string FlagText(ComparisonRow row)
    {
        var parts = new List<string>();
        if (row.AllocFlag)
            parts.Add(row.AllocDeltaPercent is double.PositiveInfinity ? "alloc (was 0 B)" : $"alloc {Signed(row.AllocDeltaPercent!.Value)}");
        if (row.TimeFlag)
            parts.Add($"time {Signed(row.TimeDeltaPercent!.Value)} (indicative)");
        if (row.Rebaselined)
            parts.Add("re-baselined");
        if (row.IsNew)
            parts.Add("new");
        return string.Join(", ", parts);
    }

    private static string FormatDelta(double? percent) => percent is null ? "-" : Signed(percent.Value) ;

    private static string Signed(double percent) =>
        double.IsPositiveInfinity(percent) ? "+inf%" : string.Create(CultureInfo.InvariantCulture, $"{percent:+0.0;-0.0;+0.0}%");

    public static string FormatTime(double ns) => ns switch
    {
        < 1_000 => string.Create(CultureInfo.InvariantCulture, $"{ns:0.##} ns"),
        < 1_000_000 => string.Create(CultureInfo.InvariantCulture, $"{ns / 1_000:0.##} us"),
        < 1_000_000_000 => string.Create(CultureInfo.InvariantCulture, $"{ns / 1_000_000:0.##} ms"),
        _ => string.Create(CultureInfo.InvariantCulture, $"{ns / 1_000_000_000:0.##} s"),
    };

    public static string FormatBytes(long bytes) => bytes switch
    {
        < 1024 => string.Create(CultureInfo.InvariantCulture, $"{bytes} B"),
        < 1024 * 1024 => string.Create(CultureInfo.InvariantCulture, $"{bytes / 1024.0:0.##} KB"),
        _ => string.Create(CultureInfo.InvariantCulture, $"{bytes / 1024.0 / 1024.0:0.##} MB"),
    };
}
